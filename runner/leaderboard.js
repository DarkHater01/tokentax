#!/usr/bin/env node
// Renders data/results.json into the README's live leaderboard block.
// Static, zero-dependency: the weekly bench job regenerates it, so the table a
// visitor reads is always the last real run and never a hand-typed number.
const fs = require("fs");
const path = require("path");

const ROOT = process.env.TOKENTAX_ROOT || path.resolve(__dirname, "..");
const START = "<!-- LEADERBOARD:START -->";
const END = "<!-- LEADERBOARD:END -->";

const tax = (n) => (n == null ? "—" : `${n}×`);
const saved = (minimal, vanilla) =>
  minimal == null || vanilla == null || !vanilla ? "—" : `${Math.round(((vanilla - minimal) / vanilla) * 100)}%`;

function render(results) {
  const entries = [...results.entries].sort((a, b) => (a.vanilla.tax ?? Infinity) - (b.vanilla.tax ?? Infinity));
  const harnesses = [...new Set(entries.map((e) => `\`${e.harness}\``))].join(", ");
  const models = entries.map((e) => `\`${e.model}\``).join(", ");
  const lines = [
    `**Live leaderboard** — last run ${String(results.generated_at).slice(0, 10)}, regenerated by [\`bench.yml\`](.github/workflows/bench.yml). Source: [\`data/results.json\`](data/results.json).`,
    "",
    `Harness ${harnesses} · models ${models} · ${Object.keys(results.tasks || {}).length} tasks · ${results.reps} reps · variants: vanilla, minimal`,
    "",
    "| # | model | `pass@1` | `tax` | `$/task` | `tax` with the minimal prompt | waste it removes |",
    "|---|---|---|---|---|---|---|",
  ];
  entries.forEach((e, i) => {
    const cost = e.vanilla.cost_per_task;
    lines.push(
      `| ${i + 1} | \`${e.model}\` | ${e.vanilla.pass_at_1.toFixed(2)} | **${tax(e.vanilla.tax)}** | ${
        cost == null ? "—" : `$${cost}`
      } | ${tax(e.minimal.tax)} | ${saved(e.minimal.tax, e.vanilla.tax)} |`
    );
  });
  lines.push("");
  lines.push(
    "Ranked by waste. `tax = 3×` means the agent spent three times what the task needed. `$/task` is 0 on free tiers, which is exactly why the ranking is the ratio and not the invoice."
  );
  return lines.join("\n");
}

function splice(readme, block) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error("README.md is missing the leaderboard markers");
  return `${readme.slice(0, a + START.length)}\n${block}\n${readme.slice(b)}`;
}

if (require.main === module) {
  const results = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "results.json"), "utf8"));
  const readmePath = path.join(ROOT, "README.md");
  fs.writeFileSync(readmePath, splice(fs.readFileSync(readmePath, "utf8"), render(results)));
  console.log("leaderboard: README.md updated from data/results.json");
}

module.exports = { render, splice, START, END };
